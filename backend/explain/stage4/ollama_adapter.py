@dataclass
class ValidationResult:
    """Result of output validation."""
    
    valid: bool
    issues: List[str] = field(default_factory=list)
    
    def __bool__(self) -> bool:
        return self.valid


class OutputValidator:
    """
    Validates LLM output to prevent hallucination and ensure quality.
    
    Checks:
      - Not empty
      - No new reasons added
      - No hallucination keywords
      - Not exceeding max length
    """
    
    def __init__(self, config: Stage4Config):
        self._config = config
    
    def validate(
        self,
        llm_output: str,
        original_text: str,
        original_reasons: List[str],
    ) -> ValidationResult:
        """
        Validate LLM output.
        
        Args:
            llm_output: Text generated by LLM
            original_text: Original text from Stage 3
            original_reasons: Original reasons from Stage 3
            
        Returns:
            ValidationResult with valid flag and issues list
        """
        issues = []
        
        # Check 1: Not empty
        if not llm_output or len(llm_output.strip()) == 0:
            issues.append("Output is empty")
            return ValidationResult(valid=False, issues=issues)
        
        # Check 2: Not exceeding max length
        if len(llm_output) > self._config.max_output_length:
            issues.append(
                f"Output too long: {len(llm_output)} > {self._config.max_output_length}"
            )
            if self._config.strict_validate:
                return ValidationResult(valid=False, issues=issues)
        
        # Check 3: Hallucination keywords
        llm_lower = llm_output.lower()
        for keyword in self._config.hallucination_keywords:
            if keyword.lower() in llm_lower:
                issues.append(f"Hallucination keyword detected: '{keyword}'")
                if self._config.strict_validate:
                    return ValidationResult(valid=False, issues=issues)
        
        # Check 4: No new significant content added (diff check)
        # This is a heuristic - check if LLM added many new words
        original_words = set(self._extract_keywords(original_text))
        llm_words = set(self._extract_keywords(llm_output))
        new_words = llm_words - original_words
        
        # Allow some variation (synonyms, rephrasing)
        if len(new_words) > len(original_words) * 0.3:
            issues.append(
                f"Too many new words added: {len(new_words)} new words"
            )
            if self._config.strict_validate:
                return ValidationResult(valid=False, issues=issues)
        
        # Valid if no critical issues
        return ValidationResult(valid=len(issues) == 0 or not self._config.strict_validate, issues=issues)
    
    def _extract_keywords(self, text: str) -> List[str]:
        """Extract significant keywords from text."""
        # Remove common Vietnamese stopwords and punctuation
        stopwords = {
            "và", "là", "của", "có", "được", "cho", "với", "trong",
            "này", "đó", "để", "như", "theo", "về", "các", "những",
            "bạn", "mô", "hình", "vì", "vì:", "...", "độ", "tin",
        }
        
        # Tokenize and filter
        words = re.findall(r'\b\w+\b', text.lower())
        return [w for w in words if w not in stopwords and len(w) > 2]


