@dataclass
class Stage4Output:
    """Output from Stage 4."""
    
    # From Stage 3
    trace_id: str
    career: str
    reasons: List[str]
    confidence: float
    raw_text: str  # Original from Stage 3
    
    # Stage 4 additions
    llm_text: str  # After Ollama formatting
    used_llm: bool
    fallback: bool = False
    
    # Metadata
    stage4_version: str = STAGE4_VERSION
    ollama_model: str = ""
    latency_ms: float = 0.0
    validation_issues: List[str] = field(default_factory=list)
    timestamp: str = ""
    
    def __post_init__(self):
        if not self.timestamp:
            self.timestamp = datetime.now(timezone.utc).isoformat()
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert to dict for API."""
        return {
            "trace_id": self.trace_id,
            "career": self.career,
            "reasons": self.reasons,
            "confidence": self.confidence,
            "raw_text": self.raw_text,
            "llm_text": self.llm_text,
            "used_llm": self.used_llm,
            "fallback": self.fallback,
            "meta": {
                "stage4_version": self.stage4_version,
                "ollama_model": self.ollama_model,
                "latency_ms": round(self.latency_ms, 2),
            },
            "timestamp": self.timestamp,
        }
    
    def to_api_response(self) -> Dict[str, Any]:
        """Convert to clean API response."""
        return {
            "trace_id": self.trace_id,
            "career": self.career,
            "reasons": self.reasons,
            "confidence": self.confidence,
            "raw_text": self.raw_text,
            "llm_text": self.llm_text,
            "used_llm": self.used_llm,
        }


# ==============================================================================
# Stage 4 Engine
# ==============================================================================

class Stage4Engine:
    """
    Stage 4 Engine - Ollama formatting.
    
    Transforms Stage 3 explanation into natural Vietnamese.
    Has mandatory fallback to Stage 3 output on any failure.
    
    Usage::
    
        engine = Stage4Engine()
        engine.load_config(config)
        
        result = engine.format(stage3_output)
    """
    
    def __init__(self, project_root: Optional[Path] = None):
        self._project_root = project_root or Path(__file__).resolve().parents[3]
        
        # Configuration
        self._config = Stage4Config()
        
        # Ollama client
        self._client = get_ollama_client()
        
        # Validator
        self._validator = OutputValidator(self._config)
        
        # Prompt template
        self._prompt_template = self._load_prompt_template()
        
        # Logging
        self._log_dir = self._project_root / "logs"
        self._log_file: Optional[Path] = None
        self._setup_logging()
        
        self._lock = threading.RLock()
    
    def _load_prompt_template(self) -> str:
        """Load prompt template from file."""
        template_path = Path(__file__).parent / "prompts" / "formatter.txt"
        if template_path.exists():
            return template_path.read_text(encoding="utf-8")
        
        # Fallback template
        return """SYSTEM:
You are a formatter. Do not add new information.
Do not change meaning.
Do not infer anything.

USER:
Rewrite the following explanation in clear Vietnamese.
Keep all facts unchanged.

TEXT:
{{ explain_text }}"""
    
    def _setup_logging(self) -> None:
        """Setup Stage 4 specific logging."""
        self._log_dir.mkdir(parents=True, exist_ok=True)
        self._log_file = self._log_dir / "explain_stage4.log"
    
    def load_config(self, config: Dict[str, Any]) -> None:
        """Load configuration."""
        self._config = Stage4Config.from_dict(config)
        
        # Update validator
        self._validator = OutputValidator(self._config)
        
        # Update client
        self._client.configure(
            model=self._config.model,
            timeout=self._config.timeout,
            max_retries=self._config.retry,
        )
        
        # Update log directory
        if self._config.log_dir:
            self._log_dir = self._project_root / self._config.log_dir
            self._setup_logging()
        
        logger.info(
            f"Stage4 config: enabled={self._config.enabled}, "
            f"model={self._config.model}, timeout={self._config.timeout}s"
        )
    
    def load_config_file(self, config_path: Optional[str] = None) -> None:
        """Load configuration from YAML file."""
        if config_path is None:
            config_path = str(self._project_root / "config" / "explain.yaml")
        
        path = Path(config_path)
        if not path.exists():
            logger.warning(f"Config file not found: {config_path}")
            return
        
        try:
            with open(path, "r", encoding="utf-8") as f:
                config = yaml.safe_load(f) or {}
            self.load_config(config)
        except Exception as e:
            logger.error(f"Failed to load config: {e}")
    
    def format(self, stage3_output: Dict[str, Any]) -> Stage4Output:
        """
        Format Stage 3 output using Ollama.
        
        Args:
            stage3_output: Output from Stage 3
            
        Returns:
            Stage4Output with formatted text or fallback
        """
        with self._lock:
            start_time = time.time()
            
            # Extract Stage 3 data
            trace_id = stage3_output.get("trace_id", "")
            career = stage3_output.get("career", "")
            reasons = stage3_output.get("reasons", [])
            confidence = float(stage3_output.get("confidence", 0.0))
            raw_text = stage3_output.get("explain_text", "")
            
            # Check if enabled
            if not self._config.enabled:
                return self._create_fallback(
                    trace_id, career, reasons, confidence, raw_text,
                    reason="Stage4 disabled"
                )
            
            # Check if raw_text is empty
            if not raw_text or len(raw_text.strip()) == 0:
                return self._create_fallback(
                    trace_id, career, reasons, confidence, raw_text,
                    reason="Empty input text"
                )
            
            # Build prompt
            prompt = self._build_prompt(raw_text)
            system_prompt = self._extract_system_prompt()
            
            # Call Ollama
            try:
                response = self._client.generate(
                    prompt=prompt,
                    system_prompt=system_prompt,
                    temperature=0.3,
                    max_tokens=500,
                )
                
                latency_ms = (time.time() - start_time) * 1000
                
                if not response.success:
                    logger.warning(f"Ollama failed: {response.error}")
                    result = self._create_fallback(
                        trace_id, career, reasons, confidence, raw_text,
                        reason=f"Ollama error: {response.error}",
                        latency_ms=latency_ms,
                    )
                    self._audit_log(result, prompt, response.text)
                    return result
                
                # Validate output
                validation = self._validator.validate(
                    response.text, raw_text, reasons
                )
                
                if not validation.valid:
                    logger.warning(f"Validation failed: {validation.issues}")
                    result = self._create_fallback(
                        trace_id, career, reasons, confidence, raw_text,
                        reason=f"Validation failed: {validation.issues}",
                        latency_ms=latency_ms,
                        validation_issues=validation.issues,
                    )
                    self._audit_log(result, prompt, response.text)
                    return result
                
                # Success
                result = Stage4Output(
                    trace_id=trace_id,
                    career=career,
                    reasons=reasons,
                    confidence=confidence,
                    raw_text=raw_text,
                    llm_text=response.text,
                    used_llm=True,
                    fallback=False,
                    ollama_model=self._config.model,
                    latency_ms=latency_ms,
                    validation_issues=validation.issues,
                )
                
                self._audit_log(result, prompt, response.text)
                return result
                
            except Exception as e:
                latency_ms = (time.time() - start_time) * 1000
                logger.error(f"Stage4 error: {e}")
                result = self._create_fallback(
                    trace_id, career, reasons, confidence, raw_text,
                    reason=f"Exception: {str(e)[:100]}",
                    latency_ms=latency_ms,
                )
                self._audit_log(result, prompt, "")
                return result
    
    def _build_prompt(self, explain_text: str) -> str:
        """Build prompt from template."""
        # Extract USER section from template
        lines = self._prompt_template.split("\n")
        user_section = []
        in_user = False
        
        for line in lines:
            if line.strip().startswith("USER:"):
                in_user = True
                continue
            if in_user:
                user_section.append(line)
        
        user_prompt = "\n".join(user_section)
        
        # Replace placeholder
        return user_prompt.replace("{{ explain_text }}", explain_text)
    
    def _extract_system_prompt(self) -> str:
        """Extract system prompt from template."""
        lines = self._prompt_template.split("\n")
        system_section = []
        in_system = False
        
        for line in lines:
            if line.strip().startswith("SYSTEM:"):
                in_system = True
                continue
            if line.strip().startswith("USER:"):
                break
            if in_system:
                system_section.append(line)
        
        return "\n".join(system_section).strip()
    
    def _create_fallback(
        self,
        trace_id: str,
        career: str,
        reasons: List[str],
        confidence: float,
        raw_text: str,
        reason: str = "",
        latency_ms: float = 0.0,
        validation_issues: Optional[List[str]] = None,
    ) -> Stage4Output:
        """Create fallback output (use Stage 3 text as-is)."""
        logger.info(f"Stage4 fallback: {reason}")
        
        return Stage4Output(
            trace_id=trace_id,
            career=career,
            reasons=reasons,
            confidence=confidence,
            raw_text=raw_text,
            llm_text=raw_text,  # Fallback to raw_text
            used_llm=False,
            fallback=True,
            ollama_model=self._config.model,
            latency_ms=latency_ms,
            validation_issues=validation_issues or [reason],
        )
    
    def _audit_log(
        self,
        result: Stage4Output,
        prompt: str,
        raw_output: str,
    ) -> None:
        """Write audit log entry."""
        if self._config.log_level == "off":
            return
        
        try:
            log_entry = {
                "timestamp": result.timestamp,
                "trace_id": result.trace_id,
                "model": result.ollama_model,
                "latency_ms": round(result.latency_ms, 2),
                "prompt_hash": hashlib.sha256(prompt.encode()).hexdigest()[:16],
                "fallback": result.fallback,
                "used_llm": result.used_llm,
            }
            
            if self._config.log_level == "full":
                log_entry["raw_output"] = raw_output[:500] if raw_output else ""
                log_entry["final_output"] = result.llm_text[:500]
                log_entry["validation_issues"] = result.validation_issues
            
            # Write to log file
            if self._log_file:
                with open(self._log_file, "a", encoding="utf-8") as f:
                    f.write(json.dumps(log_entry, ensure_ascii=False) + "\n")
            
            logger.debug(f"Stage4 audit: {result.trace_id}")
            
        except Exception as e:
            logger.error(f"Failed to write audit log: {e}")
    
    def is_enabled(self) -> bool:
        """Check if Stage 4 is enabled."""
        return self._config.enabled
    
    def health_check(self) -> bool:
        """Check if Ollama is available."""
        return self._client.health_check()


