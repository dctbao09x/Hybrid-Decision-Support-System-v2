_ANALYTICAL_PROMPT_PATH = Path(__file__).parent / "prompts" / "analytical_explanation.txt"

_STRUCTURED_EXPLANATION_KEYS: tuple[str, ...] = (
    "summary",
    "main_reasons",
    "strengths",
    "risks_or_gaps",
    "market_context",
    "next_actions",
    "confidence_explanation",
)

_EXPLANATION_STYLE_CHOICES: tuple[str, ...] = (
    "logic_first",
    "market_first",
    "strength_first",
    "risk_first",
    "comparison_first",
)

_analytical_template: Optional[str] = None


def _load_analytical_template() -> str:
    """Load (and cache) the analytical_explanation.txt prompt template."""
    global _analytical_template
    if _analytical_template is None:
        if _ANALYTICAL_PROMPT_PATH.exists():
            _analytical_template = _ANALYTICAL_PROMPT_PATH.read_text(encoding="utf-8")
        else:
            logger.warning("analytical_explanation.txt not found at %s", _ANALYTICAL_PROMPT_PATH)
            _analytical_template = ""
    return _analytical_template


def _split_system_user(template: str) -> tuple[str, str]:
    """Extract (system_prompt, user_prompt) from a SYSTEM:/USER: template."""
    system_prompt = ""
    user_prompt = template
    if "SYSTEM:" in template and "USER:" in template:
        parts = template.split("USER:", 1)
        system_part = parts[0].replace("SYSTEM:", "", 1).strip()
        system_prompt = system_part
        user_prompt = parts[1].strip()
    return system_prompt, user_prompt


def _to_float(value: Any, default: float = 0.0) -> float:
    """Convert unknown values to float safely."""
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _unique_strings(value: Any, limit: int = 4) -> List[str]:
    """Normalize an unknown value into a deduplicated list of non-empty strings."""
    if isinstance(value, list):
        raw_items = value
    elif isinstance(value, str):
        raw_items = [value]
    else:
        raw_items = []

    output: List[str] = []
    seen: set[str] = set()
    for item in raw_items:
        text = str(item).strip()
        if not text or text in seen:
            continue
        seen.add(text)
        output.append(text)
        if len(output) >= limit:
            break
    return output


def _extract_json_payload(raw_text: str) -> Optional[Dict[str, Any]]:
    """Extract a JSON object from raw LLM output text."""
    if not raw_text or not raw_text.strip():
        return None

    candidate = raw_text.strip()
    if candidate.startswith("```"):
        candidate = re.sub(r"^```(?:json)?", "", candidate, flags=re.IGNORECASE).strip()
        candidate = re.sub(r"```$", "", candidate).strip()

    candidates: List[str] = [candidate]
    start = candidate.find("{")
    end = candidate.rfind("}")
    if start >= 0 and end > start:
        candidates.append(candidate[start : end + 1])

    for payload in candidates:
        try:
            parsed = json.loads(payload)
        except Exception:
            continue
        if isinstance(parsed, dict):
            return parsed
    return None


def _normalize_structured_explanation(parsed: Dict[str, Any]) -> Dict[str, Any]:
    """Normalize parsed JSON into the required explanation schema."""
    summary = str(parsed.get("summary", "")).strip()
    main_reasons = _unique_strings(parsed.get("main_reasons"), limit=3)
    strengths = _unique_strings(parsed.get("strengths"), limit=4)
    risks_or_gaps = _unique_strings(parsed.get("risks_or_gaps"), limit=4)
    market_context = str(parsed.get("market_context", "")).strip()
    next_actions = _unique_strings(parsed.get("next_actions"), limit=4)
    confidence_explanation = str(parsed.get("confidence_explanation", "")).strip()

    if not summary and main_reasons:
        summary = main_reasons[0]
    if not summary:
        summary = "Recommendation hiện tại dựa trên các tín hiệu điểm số và quy tắc sẵn có trong dữ liệu đầu vào."

    if not main_reasons:
        main_reasons = [summary]
    if not strengths:
        strengths = ["Có tín hiệu phù hợp từ các yếu tố được chấm điểm cao hơn mặt bằng còn lại."]
    if not risks_or_gaps:
        risks_or_gaps = ["Cần thêm dữ liệu để giảm bất định của recommendation."]
    if not market_context:
        market_context = "Không có market signal đủ mạnh để thay đổi ranking hiện tại."
    if not next_actions:
        next_actions = ["Thu thập thêm dữ liệu còn thiếu và đánh giá lại recommendation."]
    if not confidence_explanation:
        confidence_explanation = "Confidence được suy ra từ độ mạnh của tín hiệu điểm số và độ đầy đủ dữ liệu đầu vào."

    normalized = {
        "summary": summary,
        "main_reasons": main_reasons,
        "strengths": strengths,
        "risks_or_gaps": risks_or_gaps,
        "market_context": market_context,
        "next_actions": next_actions,
        "confidence_explanation": confidence_explanation,
    }

    for key in _STRUCTURED_EXPLANATION_KEYS:
        normalized.setdefault(key, "" if key in {"summary", "market_context", "confidence_explanation"} else [])
    return normalized


def _select_explanation_style(runtime_payload: Dict[str, Any]) -> str:
    """Deterministically rotate explanation style to reduce template repetition."""
    requested = str(runtime_payload.get("explanation_style", "")).strip()
    if requested in _EXPLANATION_STYLE_CHOICES:
        return requested

    seed_source = json.dumps(
        {
            "top_recommendation": runtime_payload.get("top_recommendation", {}),
            "confidence_score": runtime_payload.get("confidence_score"),
            "missing_data": runtime_payload.get("missing_data", []),
            "alternative_recommendations": runtime_payload.get("alternative_recommendations", []),
        },
        ensure_ascii=False,
        sort_keys=True,
    )
    digest = hashlib.sha256(seed_source.encode("utf-8")).hexdigest()
    idx = int(digest[:8], 16) % len(_EXPLANATION_STYLE_CHOICES)
    return _EXPLANATION_STYLE_CHOICES[idx]


def _collect_feature_drivers(runtime_payload: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Extract sorted feature drivers from runtime payload."""
    raw = runtime_payload.get("feature_importance", [])
    drivers: List[Dict[str, Any]] = []

    if isinstance(raw, dict):
        for feature, impact in raw.items():
            feature_name = str(feature).strip()
            if feature_name:
                drivers.append({"feature": feature_name, "impact": _to_float(impact)})
    elif isinstance(raw, list):
        for item in raw:
            if not isinstance(item, dict):
                continue
            feature_name = str(item.get("feature") or item.get("name") or "").strip()
            if not feature_name:
                continue
            impact = _to_float(item.get("impact", item.get("score", item.get("contribution", 0.0))))
            drivers.append({"feature": feature_name, "impact": impact})

    drivers.sort(key=lambda x: abs(_to_float(x.get("impact", 0.0))), reverse=True)
    return drivers


def _build_structured_fallback(runtime_payload: Dict[str, Any]) -> Dict[str, Any]:
    """Deterministic fallback that still respects the standardized JSON schema."""
    top_recommendation = runtime_payload.get("top_recommendation", {})
    if not isinstance(top_recommendation, dict):
        top_recommendation = {}

    career = str(top_recommendation.get("career") or top_recommendation.get("name") or "ngành được đề xuất").strip()
    confidence = _to_float(
        runtime_payload.get("confidence_score", top_recommendation.get("confidence", top_recommendation.get("score", 0.0))),
        0.0,
    )

    drivers = _collect_feature_drivers(runtime_payload)
    main_reasons: List[str] = []
    strengths: List[str] = []

    if drivers:
        top_features = ", ".join([d["feature"] for d in drivers[:2]])
        main_reasons.append(
            f"Recommendation {career} được nâng bởi các score driver nổi trội: {top_features}."
        )
        strengths.extend(
            [
                f"{d['feature']} đóng góp tích cực vào mức độ phù hợp hiện tại."
                for d in drivers[:2]
                if _to_float(d.get("impact", 0.0)) > 0.0
            ]
        )

    rule_hits = runtime_payload.get("rule_hits", [])
    if isinstance(rule_hits, list) and rule_hits:
        first_rule = rule_hits[0]
        if isinstance(first_rule, dict):
            rule_name = str(first_rule.get("rule_id") or first_rule.get("rule") or "").strip()
            outcome = str(first_rule.get("outcome") or first_rule.get("status") or "").strip()
            if rule_name and outcome:
                main_reasons.append(f"Rule {rule_name} có kết quả {outcome}, ảnh hưởng trực tiếp đến xếp hạng.")
            elif rule_name:
                main_reasons.append(f"Rule {rule_name} được kích hoạt trong quá trình ra quyết định.")
        else:
            main_reasons.append(str(first_rule).strip())

    market_signals = runtime_payload.get("market_signals", [])
    market_context = "Không có market signal đủ mạnh để thay đổi ranking hiện tại."
    if isinstance(market_signals, list) and market_signals:
        signal = market_signals[0] if isinstance(market_signals[0], dict) else {}
        demand = str(signal.get("demand_level") or signal.get("demand") or "").strip()
        growth = signal.get("growth_rate")
        if demand and growth is not None:
            market_context = f"Tín hiệu thị trường hiện tại cho thấy nhu cầu {demand.lower()} với tốc độ tăng trưởng khoảng {float(growth):.2f}."
        elif demand:
            market_context = f"Tín hiệu thị trường hiện tại cho thấy nhu cầu {demand.lower()} cho nhóm nghề này."
        elif signal:
            market_context = "Có market signal hỗ trợ recommendation nhưng dữ liệu chưa đủ chi tiết để định lượng đầy đủ."

    missing_data = _unique_strings(runtime_payload.get("missing_data"), limit=4)
    negative_factors = _unique_strings(runtime_payload.get("negative_factors"), limit=4)
    risks_or_gaps = (negative_factors + [f"Thiếu dữ liệu: {item}" for item in missing_data])[:4]
    if confidence < 0.55:
        risks_or_gaps.insert(0, "Confidence hiện còn thấp, recommendation cần được xác minh thêm.")
    if not risks_or_gaps:
        risks_or_gaps = ["Chưa ghi nhận yếu tố rủi ro lớn trong dữ liệu hiện tại, nhưng vẫn cần theo dõi dữ liệu mới."]

    next_actions: List[str] = []
    if missing_data:
        next_actions.append(f"Bổ sung dữ liệu còn thiếu: {', '.join(missing_data[:3])}.")
    if negative_factors:
        next_actions.append("Ưu tiên cải thiện các yếu tố đang làm giảm mức độ phù hợp trong phần risks_or_gaps.")
    if not next_actions:
        next_actions.append("Theo dõi biến động score driver và chạy lại đánh giá khi có dữ liệu mới.")

    alternatives = runtime_payload.get("alternative_recommendations", [])
    gap_text = ""
    if isinstance(alternatives, list) and alternatives:
        alt0 = alternatives[0] if isinstance(alternatives[0], dict) else {}
        alt_name = str(alt0.get("career") or alt0.get("name") or "").strip()
        alt_score = _to_float(alt0.get("score"), 0.0)
        top_score = _to_float(top_recommendation.get("score"), 0.0)
        if alt_name and top_score > 0.0:
            gap_text = f" Chênh lệch với lựa chọn kế tiếp ({alt_name}) là {abs(top_score - alt_score):.3f}."

    if confidence >= 0.75 and not missing_data:
        confidence_explanation = "Confidence ở mức cao do tín hiệu điểm số và dữ liệu đầu vào tương đối đầy đủ." + gap_text
    elif confidence >= 0.55:
        confidence_explanation = "Confidence ở mức trung bình do một số tín hiệu mạnh nhưng vẫn còn yếu tố cần xác minh." + gap_text
    else:
        confidence_explanation = "Confidence ở mức thấp vì dữ liệu còn thiếu hoặc tín hiệu giữa các lựa chọn còn sát nhau." + gap_text

    if not main_reasons:
        main_reasons = ["Recommendation hiện tại được chọn từ tổng hợp score, rule và bằng chứng sẵn có trong input."]
    if not strengths:
        strengths = ["Có ít nhất một nhóm tín hiệu điểm số đang hỗ trợ recommendation hiện tại."]

    summary = (
        f"{career} được đề xuất vì các tín hiệu chấm điểm và quy tắc hiện tại đang nghiêng về lựa chọn này. "
        f"Mức confidence hiện tại là {confidence:.2f}, phản ánh độ chắc chắn phụ thuộc vào chất lượng dữ liệu đầu vào."
    )

    return _normalize_structured_explanation(
        {
            "summary": summary,
            "main_reasons": main_reasons[:3],
            "strengths": strengths[:4],
            "risks_or_gaps": risks_or_gaps[:4],
            "market_context": market_context,
            "next_actions": next_actions[:4],
            "confidence_explanation": confidence_explanation,
        }
    )


def generate_structured_explanation(
    runtime_payload: Dict[str, Any],
    timeout: float = 20.0,
) -> Dict[str, Any]:
    """
    Generate a standardized JSON explanation from runtime payload.

    Returns a dict matching the required schema, with deterministic fallback
    when LLM output is unavailable or invalid.
    """
    runtime_payload = runtime_payload if isinstance(runtime_payload, dict) else {}
    fallback = _build_structured_fallback(runtime_payload)

    template = _load_analytical_template()
    if not template:
        logger.warning("Analytical explanation template missing — using deterministic fallback")
        return fallback

    style = _select_explanation_style(runtime_payload)
    payload_json = json.dumps(runtime_payload, ensure_ascii=False, sort_keys=True)
    filled = (
        template.replace("{{runtime_payload}}", payload_json)
        .replace("{{explanation_style}}", style)
        .replace("{{profile_json}}", payload_json)  # backward-compatible placeholder
    )
    system_prompt, user_prompt = _split_system_user(filled)

    client = get_ollama_client()
    original_timeout = client._timeout
    try:
        client.configure(timeout=max(5.0, timeout * 0.9))
        response = client.generate(
            prompt=user_prompt,
            system_prompt=system_prompt or None,
            temperature=0.35,
            max_tokens=800,
        )
    except Exception as exc:
        logger.warning(
            "generate_structured_explanation: LLM call raised %s: %s",
            type(exc).__name__,
            exc,
        )
        return fallback
    finally:
        try:
            client.configure(timeout=original_timeout)
        except Exception:
            pass

    if not response.success or not response.text.strip():
        logger.debug(
            "generate_structured_explanation: non-success response (error=%r, text_len=%d)",
            response.error,
            len(response.text),
        )
        return fallback

    parsed = _extract_json_payload(response.text)
    if not parsed:
        logger.debug("generate_structured_explanation: failed to parse JSON payload")
        return fallback

    return _normalize_structured_explanation(parsed)


def generate_analytical_summary(
    profile_json_str: str,
    timeout: float = 20.0,
) -> str:
    """
    Backward-compatible helper returning only the summary string.

    The underlying generator now produces a standardized JSON explanation.
    """
    parsed_payload: Dict[str, Any] = {}
    try:
        loaded = json.loads(profile_json_str)
        if isinstance(loaded, dict):
            parsed_payload = loaded
    except Exception:
        parsed_payload = {}

    if "top_recommendation" not in parsed_payload:
        parsed_payload = {
            "user_profile": {
                "skills": parsed_payload.get("skills", []),
                "interests": parsed_payload.get("interests", []),
                "education_level": parsed_payload.get("education_level", ""),
                "ability_score": _to_float(parsed_payload.get("ability_score", 0.0)),
                "goals": parsed_payload.get("goals", {}),
            },
            "top_recommendation": {
                "career": parsed_payload.get("top_career", ""),
                "score": _to_float(parsed_payload.get("total_score", 0.0)),
            },
            "feature_importance": parsed_payload.get("score_breakdown", {}),
            "rule_hits": parsed_payload.get("rule_hits", []),
            "market_signals": parsed_payload.get("market_signals", []),
            "confidence_score": _to_float(
                parsed_payload.get("confidence_score", parsed_payload.get("confidence", 0.0))
            ),
            "alternative_recommendations": parsed_payload.get("alternative_recommendations", []),
            "missing_data": parsed_payload.get("missing_data", []),
        }

    structured = generate_structured_explanation(parsed_payload, timeout=timeout)
    return str(structured.get("summary", "")).strip()
