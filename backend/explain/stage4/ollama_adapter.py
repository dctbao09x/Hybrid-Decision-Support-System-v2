@dataclass
class Stage4Config:
    """Configuration for Stage 4."""
    
    enabled: bool = True
    model: str = "llama3.2:1b"
    timeout: float = 5.0
    retry: int = 2
    strict_validate: bool = True
    max_output_length: int = 2000
    log_level: str = "full"  # "full" | "minimal" | "off"
    log_dir: str = "logs"
    
    # Validation settings
    hallucination_keywords: List[str] = field(default_factory=lambda: [
        "tôi nghĩ", "có thể", "nên", "khuyên", "gợi ý",
        "thêm vào đó", "ngoài ra còn", "bạn cũng có thể",
        "theo tôi", "tôi đề xuất", "tôi khuyên",
    ])
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Stage4Config":
        """Load from config dict."""
        stage4 = data.get("stage4", data)
        return cls(
            enabled=stage4.get("enabled", True),
            model=stage4.get("model", "llama3.2:1b"),
            timeout=stage4.get("timeout", 5.0),
            retry=stage4.get("retry", 2),
            strict_validate=stage4.get("strict_validate", True),
            max_output_length=stage4.get("max_output_length", 2000),
            log_level=stage4.get("log_level", "full"),
            log_dir=stage4.get("log_dir", "logs"),
        )


